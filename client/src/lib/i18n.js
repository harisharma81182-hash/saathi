const I18nContext = createContext({ lang: LANGUAGES[0], t: (key) => TEXT.hinglish[key] ?? key });

/** Wraps the logged-in app; also sets <html lang> so screen readers and fonts pick the right language. */
export function I18nProvider({ language, children }) {
  const lang = languageById(language);
  const t = useCallback((key) => TEXT[lang.id]?.[key] ?? TEXT.en[key] ?? key, [lang.id]);
  useEffect(() => {
    document.documentElement.lang = lang.html;
  }, [lang.html]);
  const value = useMemo(() => ({ lang, t }), [lang, t]);
  return createElement(I18nContext.Provider, { value }, children);
}

export const useI18n = () => useContext(I18nContext);
